/**
 * localization.test.mjs — بررسی استاتیک HTML/CSS/رشته‌های رابط کاربری
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, check, section } from './helpers.mjs';

section('Localization (index.html / style.css)');

const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const css = fs.readFileSync(path.join(ROOT, 'style.css'), 'utf8');

check('lang="fa"', /<html\s+lang="fa"/.test(html));
check('dir="rtl"', /<html[^>]*dir="rtl"/.test(html));
check('Persian <title>', html.includes('کاوشگر فضای امبدینگ'));
check('Vazirmatn @font-face (local woff2)', css.includes("font-family: 'Vazirmatn'") && css.includes('vendor/fonts/Vazirmatn-'));
check('no Google Fonts / external font CDN', !/fonts\.googleapis|fonts\.gstatic/.test(css + html));
check('importmap uses local vendored three.js', html.includes('"three": "./vendor/three/build/three.module.js"'));
check('no unpkg/cdnjs imports', !/unpkg\.com|cdnjs\.cloudflare/.test(html));
check('data/fa.js loaded before module', html.indexOf('data/fa.js') < html.indexOf('js/main.js'));

// required methodology transparency text (exact wording from the spec)
const METHOD = 'این نمایشگر از بردارهای معنایی کلمات انگلیسی استفاده می‌کند. واژه‌ها برای سهولت استفاده به فارسی نمایش داده شده‌اند، اما موقعیت آن‌ها و روابط معنایی همچنان بر اساس مدل اصلی انگلیسی محاسبه می‌شود. بنابراین این ابزار نمایش فارسی‌شدهٔ فضای معنایی انگلیسی است، نه یک مدل Embedding فارسی.';
check('methodology disclosure present verbatim', html.includes(METHOD));

// key Persian UI strings
const required = [
    'جست‌وجوی واژه',
    'بازنشانی دوربین',
    'محاسبات برداری',
    'واژهٔ انتخاب‌شده',
    'نزدیک‌ترین همسایه‌ها',
    'دسته‌بندی‌ها',
    'روی یک واژه کلیک کنید یا جست‌وجو کنید',
    'امبدینگ واژه‌ها',
    'کاهش بُعد',
    'دربارهٔ این نمایشگر',
    'پروژه‌سازی',
    'قیاس دلخواه',
];
for (const s of required) {
    check('UI string present: «' + s + '»', html.includes(s));
}

// leftover English UI sentences (heuristic: known original strings must be gone).
// کامنت‌های توسعه‌دهنده UI نیستند → قبل از بررسی حذف می‌شوند.
const visibleHtml = html.replace(/<!--[\s\S]*?-->/g, '');
const banned = [
    'Reset Camera',
    'Vector Arithmetic</button>',
    'Search for a word',
    'Selected Word',
    'Nearest Neighbors',
    'Click a word or search',
    'Select a word to see its nearest neighbors',
    'Word Embeddings</h3>',
    'Dimensionality Reduction',
    'Categories</div>',
    '5,000 words in 3D',
];
for (const s of banned) {
    check('no leftover English UI: «' + s + '»', !visibleHtml.includes(s));
}

// CSS RTL sanity
check('info-panel uses logical border (border-inline-start)', css.includes('border-inline-start'));
check('search icon uses inset-inline-start', css.includes('inset-inline-start'));
check('no letter-spacing on Persian headings (broken-join prevention)',
    !/\.panel-title\s*\{[^}]*letter-spacing:\s*[1-9]/.test(css) &&
    !/\.logo h1\s*\{[^}]*letter-spacing:\s*-/.test(css));
check('responsive breakpoints exist', css.includes('@media (max-width: 1024px)') && css.includes('@media (max-width: 768px)'));
check('word-label direction rtl', /\.word-label\s*\{[^}]*direction:\s*rtl/s.test(css));

// JS modules: no obvious English UI literals left
// (شناسه‌ها و کامنت‌های انگلیسی کد هستند، نه متن رابط کاربری)
const jsFiles = ['js/main.js', 'js/search.js', 'js/arithmetic.js', 'js/labels.js', 'js/data.js'];
const jsBanned = ['Click a word', 'Select a word', 'Flying to analogy', 'subtracted',
                  'words in 3D', 'Nearest Neighbors'];
for (const f of jsFiles) {
    const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
    for (const s of jsBanned) {
        check(`no English UI literal in ${f}: «${s}»`, !src.includes(s));
    }
}

// Persian UI strings generated by JS must exist
const jsRequired = {
    'js/main.js': ['روی یک واژه کلیک کنید یا جست‌وجو کنید', 'نزدیک‌ترین همسایه‌های آن در فضای امبدینگ'],
    'js/search.js': ['یافت نشد', 'جست‌وجو'],
    'js/arithmetic.js': ['عبارت نامعتبر', 'در حال پرواز'],
    'js/labels.js': ['getFa'],
};
for (const [f, list] of Object.entries(jsRequired)) {
    const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
    for (const s of list) {
        check(`Persian UI string in ${f}: «${s}»`, src.includes(s));
    }
}
